async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.reload();
  await page.setViewportSize({width:1360,height:1050});
  if (await page.locator('#devices tr').count() !== 5) throw new Error('Expected 5 device rows');
  if (await page.locator('#total').innerText() !== '4.83 MiB') throw new Error('Incorrect total');
  if (await page.locator('#chart polyline').count() !== 2) throw new Error('Missing directional curves');
  await page.locator('#device').selectOption('192.168.110.211');
  await page.locator('#sample').focus();
  await page.locator('#sample').press('Home');
  await page.locator('#sample').press('ArrowRight');
  if (await page.locator('#sample').inputValue() !== '1') throw new Error('Keyboard time navigation failed');
  await page.locator('#category').selectOption('lan');
  if (!((await page.locator('#upLegend').innerText()).includes('内网发送'))) throw new Error('Wrong LAN labels');
  await page.locator('#device').selectOption('*');
  if (await page.locator('#chart polyline').count() !== 1) throw new Error('LAN aggregate is double-counted in display');
  await page.locator('#category').selectOption('service');
  if (await page.locator('#chart polyline').count() !== 1) throw new Error('Service curve incorrect');
  await page.locator('#category').selectOption('internet');
  await page.locator('#search').fill('ljj');
  if (await page.locator('#devices tr').count() !== 1) throw new Error('Search failed');
  await page.locator('#search').fill('');
  await page.locator('#sort').selectOption('up_bytes');
  if (!((await page.locator('#devices tr').first().innerText()).includes('ljj电脑'))) throw new Error('Upload ranking failed');
  await page.getByRole('button',{name:'查看 我的iPhone 的流量曲线',exact:true}).click();
  if (await page.locator('#device').inputValue() !== '192.168.110.204') throw new Error('Row curve button failed');
  await page.locator('#device').selectOption('*');
  await page.locator('#sort').selectOption('total_bytes');
  await page.evaluate(() => window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/report-desktop.png',fullPage:true});
  const [download] = await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'设备 CSV',exact:true}).click()]);
  await download.saveAs('output/playwright/downloaded-devices.csv');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => window.scrollTo(0,0));
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth+1)) throw new Error('Mobile document overflows horizontally');
  await page.screenshot({path:'output/playwright/report-mobile.png',fullPage:true});
  if (errors.length) throw new Error(JSON.stringify(errors));
  return {deviceRows:5,filters:'pass',sorting:'pass',keyboardSlider:'pass',download:'pass',mobileWidth:390,pageErrors:errors};
}
